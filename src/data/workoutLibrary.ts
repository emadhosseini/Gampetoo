// MET (Metabolic Equivalent of Task) values are approximate, per the
// Compendium of Physical Activities' general categories (moderate-vigorous
// resistance training ≈ 5.0, light cardio/warmup work differentiated
// individually below) — same "typical/average estimate, not a clinical
// source" spirit as the food databases' macros (see
// src/data/nutrition/iranianFoodsDatabase.ts). Used by
// domain/services/calorieCalculator.ts to estimate calories burned once a
// workout is checked off.
// Anatomy/reference fields below follow MuscleWiki's own taxonomy, kept in
// its English canonical form because they're categorical identifiers (the
// same role `unit` plays), not prose — the human-readable Persian text is
// `description`. Every one of them is optional: they're reference data the
// app doesn't compute anything from, so an entry without them behaves
// exactly as it always did, and older seed entries need no backfill.
export type ExerciseMechanic = "Compound" | "Isolation";

export interface Exercise {
  id: string;
  // The Persian name Iranian gyms actually use. One id always carries one
  // name everywhere it appears (an exercise reused across days keeps the
  // same wording), and no two ids share a name — assertLibraryIsConsistent
  // below enforces both, because the same movement showing up as "پرس سینه
  // دستگاه" in one day and "پرس سینه دستگاه ماشین" in another read as two
  // unrelated exercises when it's really one.
  name: string;
  // What the move is called at the source (MuscleWiki). Kept as its own
  // field rather than appended into `name` so the UI can render it smaller
  // and quieter beside the Persian name instead of as one long string.
  nameEn?: string;
  sets: number;
  // What `reps` counts. Isometric holds (planks and the like) aren't
  // repeated, they're endured, so counting them in repetitions was
  // meaningless — "۳ ست × ۱۰ تکرار پلانک" doesn't describe anything a
  // person can do. Absent means repetitions, which is almost everything.
  unit?: "reps" | "seconds";
  reps: number;
  // A per-set rep target (e.g. پیرامید ۱۲/۱۰/۸) for whoever's plan doesn't
  // use the same rep count on every set. When present, its length is the
  // real set count — `sets`/`reps` above stay in sync (sets === length,
  // reps === its last value) purely so anything that hasn't been taught
  // about this field yet still gets a sane single number. Absent — the
  // default for every seed entry and for anyone who never turns this on —
  // means "same reps on every set", exactly the old behavior.
  repsPerSet?: number[];
  enabled: boolean;
  metValue: number;
  // Two or three plain-Persian sentences: which muscle the move is mainly
  // for, what it also hits, and what it actually does for the body.
  description?: string;
  primaryMuscle?: string;
  secondaryMuscles?: string[];
  equipment?: string;
  mechanic?: ExerciseMechanic;
}

export interface ExerciseGroup {
  id: string;
  title: string;
  exercises: Exercise[];
}

// Not scoped to WorkoutType: only the original push/pull/legs/upper/lower/
// full_body/warmup entries double as an actual program day's workoutId
// (see ProgramBuilderPage). Every other entry here exists purely so the
// workout library's browsing taxonomy (workoutTaxonomy.ts) has somewhere
// to link its leaves to — most of them start out with no exercises, filled
// in later, and pruneToSelectable() (workoutTaxonomy.ts) already excludes
// anything with an empty groups list from the program-day picker
// (WorkoutPickerModal).
export interface WorkoutDefinition {
  id: string;
  title: string;
  groups: ExerciseGroup[];
}

